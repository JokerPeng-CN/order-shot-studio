import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
OUT = ROOT / "js" / "assets-data.js"

def data_url(path: Path, mime: str) -> str:
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{encoded}"

assets = {
    "chromeTop": data_url(ASSETS / "chrome-top.png", "image/png"),
    "chromeBottom": data_url(ASSETS / "chrome-bottom.png", "image/png"),
    "product": data_url(ASSETS / "product-default.jpg", "image/jpeg"),
    "amount": data_url(ASSETS / "amount-total.png", "image/png"),
}

OUT.write_text(
    "/* Generated by tools/embed-assets.py — do not edit by hand. */\n"
    "window.IMAGE_ASSETS = " + json.dumps(assets, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {OUT} ({OUT.stat().st_size:,} bytes)")
